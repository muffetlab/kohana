<?php

namespace Kohana\Database\Schema;

/**
 * PostgreSQL schema grammar.
 *
 * @package    Kohana/Database
 * @category   Schema
 */
class PostgresGrammar extends Grammar
{
    protected function type(ColumnDefinition $column): string
    {
        $p = $column->parameters;

        $type = match ($column->type) {
            'string' => 'VARCHAR(' . $p['length'] . ')',
            'char' => 'CHAR(' . $p['length'] . ')',
            'text', 'longText' => 'TEXT',
            'integer' => 'INTEGER',
            'smallInteger' => 'SMALLINT',
            'bigInteger' => 'BIGINT',
            'boolean' => 'BOOLEAN',
            'decimal' => 'NUMERIC(' . $p['precision'] . ', ' . $p['scale'] . ')',
            'float' => 'DOUBLE PRECISION',
            'date' => 'DATE',
            'dateTime', 'timestamp' => 'TIMESTAMP(0) WITHOUT TIME ZONE',
            'time' => 'TIME(0) WITHOUT TIME ZONE',
            'json' => 'JSON',
            'binary' => 'BYTEA',
            'uuid' => 'UUID',
            default => throw new \InvalidArgumentException("Unknown column type {$column->type}"),
        };

        // PostgreSQL has no unsigned types; auto-increment uses identity columns
        if ($column->autoIncrement) {
            $type .= ' GENERATED BY DEFAULT AS IDENTITY';
        }

        return $type;
    }

    protected function booleanValue(bool $value): string
    {
        return $value ? 'TRUE' : 'FALSE';
    }

    protected function compileDropIndex(Blueprint $blueprint, string $name): string
    {
        return 'DROP INDEX ' . $this->db->quoteIdentifier($name);
    }

    protected function compileDropForeign(Blueprint $blueprint, string $name): string
    {
        return 'ALTER TABLE ' . $this->table($blueprint) . ' DROP CONSTRAINT ' . $this->db->quoteIdentifier($name);
    }

    protected function compileComments(Blueprint $blueprint): array
    {
        $statements = [];

        foreach ($blueprint->columns() as $column) {
            if ($column->comment !== null) {
                $statements[] = 'COMMENT ON COLUMN ' . $this->table($blueprint) . '.' . $this->db->quoteColumn($column->name) . ' IS ' . $this->db->quote($column->comment);
            }
        }

        return $statements;
    }
}
