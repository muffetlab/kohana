/**
 * Schema builder, migrator and seeders on MySQL and PostgreSQL.
 */
#[Group('kohana')]
#[Group('kohana.database')]
#[Group('kohana.database.migrations')]
class Kohana_Database_MigrationTest extends TestCase
{
    public static function provider_connections(): array
    {
        return [['mysqli'], ['pgsql']];
    }

    protected function connect(string $name): Connection
    {
        try {
            $db = Connection::instance($name);
            $db->connect();
        } catch (Exception $e) {
            $this->markTestSkipped('Database connection failed: ' . $e->getMessage());
        }

        foreach (['mig_posts', 'mig_authors', 'mig_log', 'migrations', 'schema_test'] as $table) {
            Schema::connection($name)->dropIfExists($table);
        }

        return $db;
    }

    protected function migrator(string $name): Migrator
    {
        $files = [];
        foreach (glob(KOHANA_FIXTURES . '/migrations/*.php') as $path) {
            $files[basename($path, '.php')] = $path;
        }

        return new Migrator($name, 'migrations', $files);
    }

    /**
     * A connection that quotes like the real driver but never connects.
     */
    protected function offline(string $class): Connection
    {
        $connection = new class ('offline', ['table_prefix' => '', 'connection' => []]) extends PgsqlConnection {
            public function escape(string $value): string
            {
                return "'" . str_replace("'", "''", $value) . "'";
            }
        };

        if ($class === MySqliConnection::class) {
            (fn () => $this->identifier = '`')->call($connection);
        }

        return $connection;
    }

    // -- Grammar (no database needed) -------------------------------------------

    public function test_mysql_grammar()
    {
        $grammar = new MySqlGrammar($this->offline(MySqliConnection::class));

        $blueprint = new Blueprint('posts', true);
        $blueprint->id();
        $blueprint->string('title', 100)->comment('Title');
        $blueprint->boolean('published')->default(false);
        $blueprint->decimal('price', 10, 2)->unsigned()->nullable();
        $blueprint->index(['title', 'published']);

        $this->assertSame([
            'CREATE TABLE `posts` (`id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, `title` VARCHAR(100) NOT NULL COMMENT \'Title\', '
            . '`published` TINYINT(1) NOT NULL DEFAULT 0, `price` DECIMAL(10, 2) UNSIGNED NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4',
            'CREATE INDEX `posts_title_published_index` ON `posts` (`title`, `published`)',
        ], $grammar->compile($blueprint));
    }

    public function test_postgres_grammar()
    {
        $grammar = new PostgresGrammar($this->offline(PgsqlConnection::class));

        $blueprint = new Blueprint('posts', true);
        $blueprint->id();
        $blueprint->boolean('published')->default(true);
        $blueprint->json('meta')->nullable()->comment('Extra');

        $this->assertSame([
            'CREATE TABLE "posts" ("id" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, "published" BOOLEAN NOT NULL DEFAULT TRUE, "meta" JSON NULL)',
            'COMMENT ON COLUMN "posts"."meta" IS \'Extra\'',
        ], $grammar->compile($blueprint));
    }

    // -- Against a database -----------------------------------------------------

    #[DataProvider('provider_connections')]
    public function test_schema_builder(string $name)
    {
        $db = $this->connect($name);
        $schema = Schema::connection($name);

        $schema->create('schema_test', function (Blueprint $table) {
            $table->id();
            $table->string('email')->unique();
            $table->integer('votes')->default(0);
            $table->text('bio')->nullable();
            $table->json('meta')->nullable();
            $table->timestamps();
        });

        $this->assertTrue($schema->hasTable('schema_test'));
        $this->assertTrue($schema->hasColumn('schema_test', 'votes'));

        [$id] = DB::insert('schema_test', ['email'])->values(['a@example.com'])->execute($db);
        $this->assertSame(1, (int) $id);
        $this->assertSame(0, (int) DB::select('votes')->from('schema_test')->execute($db)->get('votes'));

        try {
            DB::insert('schema_test', ['email'])->values(['a@example.com'])->execute($db);
            $this->fail('The unique index should reject a duplicate');
        } catch (DatabaseException $e) {
        }

        $schema->table('schema_test', function (Blueprint $table) {
            $table->string('name')->nullable();
            $table->renameColumn('bio', 'about');
            $table->dropColumn('meta');
        });

        $columns = array_keys($db->listColumns('schema_test'));
        $this->assertContains('name', $columns);
        $this->assertContains('about', $columns);
        $this->assertNotContains('bio', $columns);
        $this->assertNotContains('meta', $columns);

        $schema->rename('schema_test', 'schema_test_renamed');
        $this->assertFalse($schema->hasTable('schema_test'));
        $schema->drop('schema_test_renamed');
        $this->assertFalse($schema->hasTable('schema_test_renamed'));
    }

    #[DataProvider('provider_connections')]
    public function test_migrate_status_and_rollback(string $name)
    {
        $db = $this->connect($name);
        $migrator = $this->migrator($name);

        $this->assertSame([
            '2026_01_01_000001_create_mig_authors_table' => null,
            '2026_01_01_000002_create_mig_posts_table' => null,
            '2026_01_01_000003_add_slug_to_mig_posts_table' => null,
        ], $migrator->status());

        $notified = [];
        $ran = $migrator->migrate(function ($migration) use (&$notified) {
            $notified[] = $migration;
        });

        $this->assertCount(3, $ran);
        $this->assertSame($ran, $notified);
        $this->assertSame([1, 1, 1], array_values($migrator->status()));
        $this->assertContains('slug', array_keys($db->listColumns('mig_posts')));
        $this->assertSame([], $migrator->migrate(), 'Nothing left to run');

        // The foreign key cascades
        [$author] = DB::insert('mig_authors', ['name'])->values(['Ayşe'])->execute($db);
        DB::insert('mig_posts', ['mig_author_id', 'title'])->values([$author, 'Hi'])->execute($db);
        DB::delete('mig_authors')->execute($db);
        $this->assertCount(0, DB::select()->from('mig_posts')->execute($db));

        // One step back, then the rest
        $this->assertSame(['2026_01_01_000003_add_slug_to_mig_posts_table'], $migrator->rollback(1));
        $this->assertNotContains('slug', array_keys($db->listColumns('mig_posts')));
        $this->assertNull($migrator->status()['2026_01_01_000003_add_slug_to_mig_posts_table']);

        // A new run gets the next batch number
        $migrator->migrate();
        $this->assertSame(2, $migrator->status()['2026_01_01_000003_add_slug_to_mig_posts_table']);

        // Rolling back the last batch only reverts batch 2
        $this->assertSame(['2026_01_01_000003_add_slug_to_mig_posts_table'], $migrator->rollback());

        $this->assertSame(['2026_01_01_000002_create_mig_posts_table', '2026_01_01_000001_create_mig_authors_table'], $migrator->rollback(0, true));
        $this->assertFalse(Schema::connection($name)->hasTable('mig_authors'));
    }

    #[DataProvider('provider_connections')]
    public function test_seeders(string $name)
    {
        $db = $this->connect($name);
        $this->migrator($name)->migrate();

        $previous = Connection::$default;
        $seeded = [];
        Seeder::seed(MigAuthorSeeder::class, $name, function ($class) use (&$seeded) {
            $seeded[] = $class;
        });

        $this->assertSame($previous, Connection::$default, 'The default connection is restored');
        $this->assertSame([MigAuthorSeeder::class, Database\Seeders\MigPostSeeder::class], $seeded);
        $this->assertSame(['Ali', 'Ayşe'], DB::select('name')->from('mig_authors')->orderBy('name')->execute($db)->asArray(null, 'name'));
        $this->assertSame('Merhaba', DB::select('title')->from('mig_posts')->execute($db)->get('title'));

        $this->migrator($name)->rollback(0, true);
    }

    public function test_seeder_must_extend_base_class()
    {
        $this->expectException(DatabaseException::class);

        Seeder::seed(stdClass::class);
    }

    // -- make:migration ---------------------------------------------------------

    public static function provider_migration_stubs(): array
    {
        return [
            ['create_posts_table', null, null, "Schema::create('posts'", "Schema::dropIfExists('posts');"],
            ['add_slug_to_posts_table', null, null, "Schema::table('posts'", "Schema::table('posts'"],
            ['remove_slug_from_posts_table', null, null, "Schema::table('posts'", "Schema::table('posts'"],
            ['tweak_things', 'things', null, "Schema::create('things'", "Schema::dropIfExists('things');"],
            ['tweak_things', null, 'things', "Schema::table('things'", "Schema::table('things'"],
            ['tweak_things', null, null, '//', '//'],
        ];
    }

    #[DataProvider('provider_migration_stubs')]
    public function test_migration_stub(string $name, ?string $create, ?string $table, string $up, string $down)
    {
        $source = MigrationCommand::stub($name, $create, $table);

        [$upBody, $downBody] = explode('public function down(): void', $source);
        $this->assertStringContainsString($up, $upBody);
        $this->assertStringContainsString($down, $downBody);

        $file = tempnam(sys_get_temp_dir(), 'migration');
        file_put_contents($file, $source);
        exec(escapeshellarg(PHP_BINARY) . ' -l ' . escapeshellarg($file), $lint, $status);
        $migration = require $file;
        unlink($file);

        $this->assertSame(0, $status);
        $this->assertInstanceOf(Kohana\Database\Migrations\Migration::class, $migration);
    }
}
