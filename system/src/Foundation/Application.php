    /**
     * Provides simple file-based caching for strings and arrays:
     *
     *     // Set the "foo" cache
     *     Kohana::cache('foo', 'hello, world');
     *
     *     // Get the "foo" cache
     *     $foo = Kohana::cache('foo');
     *
     * All caches are stored as PHP code, generated with [var_export][ref-var].
     * Caching objects may not work as expected. Storing references or an
     * object or array that has recursion will cause an E_FATAL.
     *
     * The cache directory and default cache lifetime is set by [Kohana::init]
     *
     * [ref-var]: https://www.php.net/var_export
     *
     * @param string $name Name of the cache
     * @param   mixed   $data       data to cache
     * @param int|null $lifetime Number of seconds the cache is valid for
     * @return  mixed|bool The cached data when getting, or a boolean when setting.
     */
    public static function cache(string $name, $data = null, ?int $lifetime = null)
    {
        // Cache file is a hash of the name
        $file = sha1($name) . '.txt';

        // Cache directories are split by keys to prevent filesystem overload
        $dir = static::$cacheDir . DIRECTORY_SEPARATOR . $file[0] . $file[1] . DIRECTORY_SEPARATOR;

        if ($lifetime === null) {
            // Use the default lifetime
            $lifetime = static::$cacheLife;
        }

        if ($data === null) {
            if (is_file($dir . $file)) {
                if (time() - filemtime($dir . $file) < $lifetime) {
                    // Return the cache
                    try {
                        return unserialize(file_get_contents($dir . $file));
                    } catch (\Exception $e) {
                        // Cache is corrupt, let return happen normally.
                    }
                } else {
                    try {
                        // Cache has expired
                        unlink($dir . $file);
                    } catch (\Exception $e) {
                        // Cache has mostly likely already been deleted,
                        // let return happen normally.
                    }
                }
            }

            // Cache not found
            return null;
        }

        if (!is_dir($dir)) {
            // Create the cache directory
            mkdir($dir, 0777, true);

            // Set permissions (must be manually set to fix umask issues)
            chmod($dir, 0777);
        }

        // Force the data to be a string
        $data = serialize($data);

        try {
            // Write the cache
            return (bool) file_put_contents($dir . $file, $data, LOCK_EX);
        } catch (\Exception $e) {
            // Failed to write cache
            return false;
        }
    }

    /**
     * Get a message from a file. Messages are arbitrary strings that are stored
     * in the `messages/` directory and reference by a key. Translation is not
     * performed on the returned values.  See [message files](kohana/files/messages)
     * for more information.
     *
     *     // Get "username" from messages/text.php
     *     $username = Kohana::message('text', 'username');
     *
     * @param string $file File name
     * @param string|null $path Key path to get
     * @param   mixed   $default    default value if the path does not exist
     * @return string|array Returns the message string for the given path, or the entire message array if no path is specified.
     * @uses    Arr::merge
     * @uses    Arr::path
     */
    public static function message(string $file, ?string $path = null, $default = null)
    {
        static $messages;

        if (!isset($messages[$file])) {
            // Create a new message list
            $messages[$file] = [];

            if ($files = static::findFile('messages', $file)) {
                foreach ($files as $f) {
                    // Combine all the messages recursively
                    $messages[$file] = Arr::merge($messages[$file], (array) static::load($f));
                }
            }
        }

        if ($path === null) {
            // Return all the messages
            return $messages[$file];
        } else {
            // Get a message using the path
            return Arr::path($messages[$file], $path, $default);
        }
    }

    /**
     * PHP error handler, converts all errors into ErrorExceptions. This handler
     * respects error_reporting settings.
     *
     * @throws  ErrorException
     * @return  true
     */
    public static function errorHandler($code, $error, $file = null, $line = null): bool
    {
        if (error_reporting() & $code) {
            // This error is not suppressed by current error reporting settings
            // Convert the error into an ErrorException
            throw new \ErrorException($error, $code, 0, $file, $line);
        }

        // Do not execute the PHP error handler
        return true;
    }

    /**
     * Catches errors that are not caught by the error handler, such as E_PARSE.
     *
     * @return  void
     * @throws Kohana_Exception
     * @uses    Kohana_Exception::handler
     */
    public static function shutdownHandler()
    {
        if (!static::$init) {
            // Do not execute when not active
            return;
        }

        try {
            if (static::$caching === true && static::$filesChanged === true) {
                // Write the file path cache
                static::cache('Kohana\Foundation\Application::find_file()', static::$files);
            }
        } catch (\Exception $e) {
            // Pass the exception to the handler
            KohanaException::handler($e);
        }

        if (static::$errors && ($error = error_get_last()) && in_array($error['type'], static::$shutdownErrors)) {
            // Clean the output buffer
            ob_get_level() and ob_clean();

            // Fake an exception for nice debugging
            KohanaException::handler(new \ErrorException($error['message'], $error['type'], 0, $error['file'], $error['line']));

            // Shutdown now to avoid a "death loop"
            exit(1);
        }
    }

    /**
     * Generates a version string based on the variables defined above.
     *
     * @return string
     */
    public static function version(): string
    {
        return 'Kohana Framework ' . static::VERSION;
    }
