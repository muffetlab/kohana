     * `string`  | charset    | Character set used for all input and output    | `"utf-8"`
     * `string`  | cache_dir  | Kohana's cache directory.  Used by [Kohana::cache] for simple internal caching, like [Fragments](kohana/fragments) and **\[caching database queries](this should link somewhere)**.  This has nothing to do with the [Cache module](cache). | `APPPATH."cache"`
     * `integer` | cache_life | Lifetime, in seconds, of items cached by [Kohana::cache]         | `60`
     * `boolean` | errors     | Should Kohana catch PHP errors and uncaught Exceptions and show the `error_view`. See [Error Handling](kohana/errors) for more info. <br /> <br /> Recommended setting: `true` while developing, `false` on production servers. | `true`
     * `boolean` | profile    | Whether to enable the [Profiler](kohana/profiling). <br /> <br />Recommended setting: `true` while developing, `false` on production servers. | `true`
     * `boolean` | caching    | Cache file locations to speed up [Kohana::find_file].  This has nothing to do with [Kohana::cache], [Fragments](kohana/fragments) or the [Cache module](cache).  <br /> <br />  Recommended setting: `false` while developing, `true` on production servers. | `false`
     * `boolean` | expose     | Set the X-Powered-By header
     *
     * @param array|null $settings Array of settings. See above.
     * @return  void
     * @throws Kohana_Exception
     * @uses    Kohana::globals
     * @uses    Kohana::sanitize
     * @uses    Kohana::cache
     * @uses    Profiler
     */
    public static function init(?array $settings = null)
    {
        if (static::$init) {
            // Do not allow execution twice
            return;
        }

        // Kohana is now initialized
        static::$init = true;

        if (isset($settings['profile'])) {
            // Enable profiling
            static::$profiling = (bool) $settings['profile'];
        }

        // Start an output buffer
        ob_start();

        if (isset($settings['errors'])) {
            // Enable error handling
            static::$errors = (bool) $settings['errors'];
        }

        if (static::$errors === true) {
            // Enable Kohana exception handling, adds stack traces and error source.
            set_exception_handler([KohanaException::class, 'handler']);

            // Enable Kohana error handling, converts all PHP errors to exceptions.
            set_error_handler([Application::class, 'errorHandler']);
        }

        // Enable the Kohana shutdown handler, which catches E_FATAL errors.
        register_shutdown_function([Application::class, 'shutdownHandler']);

        if (isset($settings['expose'])) {
            static::$expose = (bool) $settings['expose'];
        }

        // Determine if we are running in a Windows environment
        static::$isWindows = DIRECTORY_SEPARATOR === '\\';

        if (isset($settings['cache_dir'])) {
            if (!is_dir($settings['cache_dir'])) {
                try {
                    // Create the cache directory
                    mkdir($settings['cache_dir'], 0755, true);

                    // Set permissions (must be manually set to fix umask issues)
                    chmod($settings['cache_dir'], 0755);
                } catch (\Exception $e) {
                    throw new KohanaException('Could not create cache directory :dir', [':dir' => Debug::path($settings['cache_dir'])]);
                }
            }

            // Set the cache directory path
            static::$cacheDir = realpath($settings['cache_dir']);
        } else {
            // Use the default cache directory
            static::$cacheDir = APPPATH . 'cache';
        }

        if (!is_writable(static::$cacheDir)) {
            throw new KohanaException('Directory :dir must be writable', [':dir' => Debug::path(static::$cacheDir)]);
        }

        if (isset($settings['cache_life'])) {
            // Set the default cache lifetime
            static::$cacheLife = (int) $settings['cache_life'];
        }

        if (isset($settings['caching'])) {
            // Enable or disable internal caching
            static::$caching = (bool) $settings['caching'];
        }

        if (static::$caching === true) {
            // Load the file path cache
            static::$files = static::cache('Kohana\Foundation\Application::find_file()');
        }

        if (isset($settings['charset'])) {
            // Set the system character set
            static::$charset = strtolower($settings['charset']);
        }

        if (function_exists('mb_internal_encoding')) {
            // Set the MB extension encoding to the same character set
            mb_internal_encoding(static::$charset);
        }

        if (isset($settings['base_url'])) {
            // Set the base URL
            static::$baseUrl = rtrim($settings['base_url'], '/') . '/';
        }

        if (isset($settings['index_file'])) {
            // Set the index file
            static::$indexFile = trim($settings['index_file'], '/');
        }

        // Sanitize all request variables
        $_GET = static::sanitize($_GET);
        $_POST = static::sanitize($_POST);
        $_COOKIE = static::sanitize($_COOKIE);

        // Load the logger if one doesn't already exist
        if (!static::$log instanceof Logger) {
            static::$log = Logger::instance();
        }

        // Load the config if one doesn't already exist
        if (!static::$config instanceof Repository) {
            static::$config = new Repository;
        }
    }

    /**
     * Cleans up the environment:
     *
     * - Restore the previous error and exception handlers
     * - Destroy the Kohana::$log and Kohana::$config objects
     *
     * @return  void
     */
    public static function deinit()
    {
        if (static::$init) {
            // Removed the autoloader
            spl_autoload_unregister([Application::class, 'autoLoad']);

            if (static::$errors) {
                // Go back to the previous error handler
                restore_error_handler();

                // Go back to the previous exception handler
                restore_exception_handler();
            }

            // Destroy objects created by init
            static::$log = static::$config = null;

            // Reset internal storage
            static::$modules = static::$files = [];
            static::$paths = [APPPATH, SYSPATH];

            // Reset file cache status
            static::$filesChanged = false;

            // Kohana is no longer initialized
            static::$init = false;
        }
    }

    /**
     * Recursively sanitizes an input variable:
     *
     * - Normalizes all newlines to LF
     *
     * @param   mixed   $value  any variable
     * @return  mixed   sanitized variable
     */
    public static function sanitize($value)
    {
        if (is_array($value) || is_object($value)) {
            foreach ($value as $key => $val) {
                // Recursively clean each value
                $value[$key] = static::sanitize($val);
            }
        } elseif (is_string($value)) {
            if (strpos($value, "\r") !== false) {
                // Standardize newlines
                $value = str_replace(["\r\n", "\r"], "\n", $value);
            }
        }

        return $value;
    }

    /**
     * Provides autoloading support of classes that follow Kohana's [class
     * naming conventions](kohana/conventions#class-names-and-file-location).
     * See [Loading Classes](kohana/autoloading) for more information.
     *
     *     // Loads classes/My/Class/Name.php
     *     Kohana::auto_load('My_Class_Name');
     *
     * or with a custom directory:
     *
     *     // Loads vendor/My/Class/Name.php
     *     Kohana::auto_load('My_Class_Name', 'vendor');
     *
     * You should never have to call this function, as simply calling a class
     * will cause it to be called.
     *
     * This function must be enabled as an autoloader in the bootstrap:
     *
     *     spl_autoload_register(['Kohana', 'auto_load']);
     *
     * @param string $class Class name
     * @param string $directory Directory to load from
     * @return  bool
     */
    public static function autoLoad(string $class, string $directory = 'classes'): bool
    {
        // Transform the class name according to PSR-0
        $class = ltrim($class, '\\');
        $file = '';
        $namespace = '';

        if ($last_namespace_position = strripos($class, '\\')) {
            $namespace = substr($class, 0, $last_namespace_position);
            $class = substr($class, $last_namespace_position + 1);
            $file = str_replace('\\', DIRECTORY_SEPARATOR, $namespace) . DIRECTORY_SEPARATOR;
        }

        $file .= str_replace('_', DIRECTORY_SEPARATOR, $class);

        if ($path = static::findFile($directory, $file)) {
            // Load the class file
            require $path;

            // Class has been found
            return true;
        }

        // Class is not in the filesystem
        return false;
    }

    /**
     * Provides autoloading support of classes that follow Kohana's old class
     * naming conventions.
     *
     * This is included for compatibility purposes with older modules.
     *
     * @param string $class Class name
     * @param string $directory Directory to load from
     * @return  bool
     */
    public static function autoLoadLowercase(string $class, string $directory = 'classes'): bool
    {
        // Transform the class name into a path
        $file = str_replace('_', DIRECTORY_SEPARATOR, strtolower($class));

        if ($path = static::findFile($directory, $file)) {
            // Load the class file
            require $path;

            // Class has been found
            return true;
        }

        // Class is not in the filesystem
        return false;
    }

    /**
     * Changes the currently enabled modules. Module paths may be relative
     * or absolute, but must point to a directory:
     *
     *     Kohana::modules(['modules/foo', MODPATH . 'bar']);
     *
     * @param array|null $modules list of module paths
     * @return  array   enabled modules
     * @throws Kohana_Exception
     */
    public static function modules(?array $modules = null): array
    {
        if ($modules === null) {
            // Not changing modules, just return the current set
            return static::$modules;
        }

        // Start a new list of include paths, APPPATH first
        $paths = [APPPATH];

        foreach ($modules as $name => $path) {
            if (is_dir($path)) {
                // Add the module to include paths
                $paths[] = $modules[$name] = realpath($path) . DIRECTORY_SEPARATOR;
            } else {
                // This module is invalid, remove it
                throw new KohanaException('Attempted to load an invalid or missing module \':module\' at \':path\'', [
                        ':module' => $name,
                        ':path' => Debug::path($path),
                ]);
            }
        }

        // Finish the include paths by adding SYSPATH
        $paths[] = SYSPATH;

        // Set the new include paths
        static::$paths = $paths;

        // Set the current module list
        static::$modules = $modules;

        foreach (static::$modules as $path) {
            $init = $path . 'init.php';

            if (is_file($init)) {
                // Include the module initialization file once
                require_once $init;
            }
        }

        return static::$modules;
    }

